"""Typed graph state for the Nimbus triage agent (PLAN 4.4).

Plain TypedDict with total=False: every node returns only the keys it owns and
LangGraph merges partial updates. No reducers — the failure path is terminal,
so a key is written by at most one node per run.
"""

from __future__ import annotations

from typing import Any, TypedDict


class AgentState(TypedDict, total=False):
    ticket_id: str
    trace_id: str  # per-run id for trace_events; generated by intake if absent
    subject: str
    body: str

    triage: dict[str, Any]  # TriageResult.to_dict()
    plan: str
    action_proposed: bool
    action: dict[str, Any]
    action_context: dict[str, Any]
    retrieved: list[dict[str, Any]]  # RetrievedChunk.to_dict() list
    grounding: dict[str, Any]  # {supported, reason_code, score, claims}

    draft: str | None
    citations: list[str]

    flags: list[str]  # e.g. ["injection_suspected"]; flags only, never policy

    # Terminal-ish labels: draft_ready | escalated | failed | sent
    # (sent is the in-graph label; tickets.agent_outcome maps sent ->
    # action_proposed because the DB enum has no 'sent').
    outcome: str
    escalation: dict[str, Any] | None  # {reason_code, detail, queue?}
    approval: dict[str, Any] | None  # human decision captured at the gate

    step_count: int
    errors: list[str]
    failure: bool
